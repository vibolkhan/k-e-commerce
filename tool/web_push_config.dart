// Writes web/firebase-config.js for the web push service worker (F07) from
// the same config file the app is built with:
//
//   dart run tool/web_push_config.dart [config/env.json]
//
// Run it before `flutter run -d chrome` or `flutter build web`. The output is
// gitignored; the web Firebase config is public by design, but it differs per
// environment.
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final source = File(args.isEmpty ? 'config/env.json' : args.first);
  final env = (jsonDecode(source.readAsStringSync()) as Map)
      .cast<String, Object?>();
  String value(String key) => (env[key] as String?)?.trim() ?? '';

  final config = {
    'apiKey': value('FIREBASE_WEB_API_KEY'),
    'appId': value('FIREBASE_WEB_APP_ID'),
    'messagingSenderId': value('FIREBASE_MESSAGING_SENDER_ID'),
    'projectId': value('FIREBASE_PROJECT_ID'),
  };
  final out = File('web/firebase-config.js');
  if (config.values.any((v) => v.isEmpty)) {
    if (out.existsSync()) out.deleteSync();
    stdout.writeln(
      'Web Firebase keys missing in ${source.path}; web push is off.',
    );
    return;
  }
  out.writeAsStringSync(
    '// Generated by tool/web_push_config.dart — do not edit or commit.\n'
    'self.K_FIREBASE_CONFIG = ${jsonEncode(config)};\n',
  );
  stdout.writeln('Wrote ${out.path} for project ${config['projectId']}.');
}
